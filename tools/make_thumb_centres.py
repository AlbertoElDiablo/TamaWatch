"""How far to move each 38 x 38 thumbnail up or down so the creature sits in the middle of a box
(the thumbnails stand the creature on the floor of its square).

usage: python3 make_thumb_centres.py <TamaWatch>

Reads resources/drawables/thumbs/thumbs.png (16 per row) and writes source/ThumbCentres.mc:
DY[n - 1] = the square's middle minus the middle of the creature's opaque pixels.
"""
import os, sys
from PIL import Image

APP = sys.argv[1]
T = 38
im = Image.open(os.path.join(APP, "resources", "drawables", "thumbs", "thumbs.png")).convert("RGBA")
dy = []
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import region as R
for n in range(1, R.COUNT + 1):
    x0, y0 = ((n - 1) % 16) * T, ((n - 1) // 16) * T
    bb = im.crop((x0, y0, x0 + T, y0 + T)).getchannel("A").getbbox()
    dy.append(0 if bb is None else round(T / 2 - (bb[1] + bb[3]) / 2))
src = ("import Toybox.Lang;\n\n// Generated by tools/make_thumb_centres.py: per species, how far to move its 38 x 38 thumbnail\n"
       "// down (negative: up) so the creature is centred in a box rather than standing on its floor.\n"
       "module ThumbCentres {\n    const DY = [" + ", ".join(str(d) for d in dy) + "];\n}\n")
open(os.path.join(APP, "source", "ThumbCentres.mc"), "w").write(src)
print("thumb centres: dy %d..%d" % (min(dy), max(dy)))
