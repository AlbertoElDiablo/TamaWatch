# Route Crossing's walking trainers: tools/walkers.png, two rows (the boy, the girl) of 8 frames in
# 20 x 28 cells (front, back, left, right standing, then the same walking), each figure standing
# on its cell's floor. Here at 2x (the partner's zoom on the home screen), each in its own 48 x 72 cell after the two big ones: cell
# 2 + character * 8 + view * 2 + frame (views 0 front, 1 back, 2 left, 3 right), centred, on the
# cell's floor.
img = Image.new("RGBA", (36 * 48, 72), (0, 0, 0, 0))
walk = Image.open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "walkers.png")).convert("RGBA")
# The big figures (the trainer card, the character choice): cells 0 (the boy) and 1 (the girl), the
# same drawings as on the route, standing facing front, at 3x (16 x 24: the 48 x 72 cell exactly),
# on the cell's floor. (A and B above: the first figures, no longer drawn.)
# The card and the choice draw these figures themselves from their pixels (source/KidArt.mc, written
# here): every pixel a square of whole screen pixels at any screen size, never a resized bitmap
# (shrunk from 3x, some pixels came out 2 wide, some 3).
kid_runs = []
for k in range(2):
    fr = walk.crop((0, k * 28, 20, k * 28 + 28))
    fr = fr.crop(fr.getbbox())
    px = fr.load()
    runs = []
    for y in range(fr.height):
        x = 0
        while x < fr.width:
            p = px[x, y]
            if p[3] < 128:
                x += 1
                continue
            s0 = x
            while x < fr.width and px[x, y][:3] == p[:3] and px[x, y][3] >= 128:
                x += 1
            runs += [s0 | y << 5 | (x - s0) << 10, p[0] << 16 | p[1] << 8 | p[2]]
    kid_runs.append((fr.width, fr.height, runs))
    big = fr.resize((fr.width * 3, fr.height * 3), Image.NEAREST)
    img.alpha_composite(big, (k * 48 + (48 - big.width) // 2, 72 - big.height))
km = os.path.join(APP, "source", "KidArt.mc")
open(km, "w").write('''import Toybox.Graphics;
import Toybox.Lang;

// GENERATED by tools/make_trainer_art.py - do not edit by hand.
// The two big trainer figures (the card, the character choice), pixel by pixel from
// tools/walkers.png (its front view): per figure its width, height and runs, two numbers a run
// (x | y << 5 | length << 10, then its colour).
module KidArt {
    function size(g) { return g == 0 ? [%d, %d] : [%d, %d]; }
    function runs(g) {
        if (g == 0) { return [%s]; }
        return [%s];
    }
}
''' % (kid_runs[0][0], kid_runs[0][1], kid_runs[1][0], kid_runs[1][1],
       ", ".join(str(v) for v in kid_runs[0][2]), ", ".join(str(v) for v in kid_runs[1][2])))
print("kid runs", len(kid_runs[0][2]) // 2, len(kid_runs[1][2]) // 2)
