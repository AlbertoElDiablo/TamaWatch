"""Convert TamaPoke's idle-screen scenery into TamaWatch background resources.

usage: python3 make_backgrounds.py <rendered scenes dir> <TamaPoke repo> <TamaWatch>

The scenes are TamaPoke's own drawing code (MIT), rendered at 466x466 without UI,
pet or resident Pokemon (b<biome>_<dawn|day|dusk|night>.ppm, biome 0-6).
Each is scaled to 280x280 and Floyd-Steinberg dithered onto the watch's 64-colour
palette: the soft pastels sit between its colours, and snapping them to the nearest
one turns sand pink and skies grey. ~78 KB in memory per background, one at a time.
The biome per Pokemon comes from TamaPoke's dex.h (by primary type).
Generates resources/drawables/backgrounds/, backgrounds.xml and source/Scenes.mc.
"""
import os, re, sys
from PIL import Image

SCENES, TAMAPOKE, APP = sys.argv[1], sys.argv[2], sys.argv[3]
TIMES = ["dawn", "day", "dusk", "night"]
BIOMES = ["meadow", "beach", "forest", "volcano", "mountain", "snow", "graveyard"]
SIZE = 280
LEVELS = [0, 85, 170, 255]

# The watch's 64 colours (every combination of LEVELS) as a palette image for dithering.
PAL_IMG = Image.new("P", (1, 1))
_pal = [c for r in LEVELS for g in LEVELS for b in LEVELS for c in (r, g, b)]
PAL_IMG.putpalette(_pal + [0, 0, 0] * (256 - 64))

out_dir = os.path.join(APP, "resources", "drawables", "backgrounds")
os.makedirs(out_dir, exist_ok=True)

xml = []
for b in range(7):
    for t in TIMES:
        im = Image.open(os.path.join(SCENES, "b%d_%s.ppm" % (b, t))).convert("RGB")
        im = im.resize((SIZE, SIZE), Image.LANCZOS)
        im = im.quantize(palette=PAL_IMG, dither=Image.Dither.FLOYDSTEINBERG).convert("RGB")
        cols = sorted(c for _, c in im.getcolors(1 << 16))
        rid = "bg%d_%s" % (b, t)
        im.save(os.path.join(out_dir, rid + ".png"), optimize=True)
        pal = "".join("<color>%02X%02X%02X</color>" % c for c in cols)
        xml.append('    <bitmap id="%s" filename="backgrounds/%s.png"><palette disableTransparency="true">%s</palette></bitmap>' % (rid, rid, pal))

with open(os.path.join(APP, "resources", "drawables", "backgrounds.xml"), "w") as f:
    f.write("<drawables>\n" + "\n".join(xml) + "\n</drawables>\n")

# biome per dex number, from TamaPoke's dex.h: the 12th field of each DEX_TBL row
biome = {}
for line in open(os.path.join(TAMAPOKE, "dex.h"), encoding="utf-8"):
    m = re.match(r'\s*\{\s*"[^"]*",(.*)\},\s*//\s*(\d+)', line)
    if m:
        fields = [x.strip() for x in m.group(1).split(",")]
        biome[int(m.group(2))] = int(fields[10])
missing = [n for n in range(1, 152) if n not in biome]
assert not missing, missing
digits = "".join(str(biome[n]) for n in range(1, 152))

with open(os.path.join(APP, "source", "Scenes.mc"), "w") as f:
    f.write('''// GENERATED by tools/make_backgrounds.py - do not edit by hand.
// Backgrounds: TamaPoke's idle scenery (MIT, https://github.com/crenberries428/TamaPoke).
import Toybox.Lang;
import Toybox.WatchUi;

module Scenes {

    // Biome per dex number 1-151 (0 meadow, 1 beach, 2 forest, 3 volcano,
    // 4 mountain, 5 snow, 6 graveyard), as TamaPoke assigns them by primary type.
    const BIOMES = "%s";

    function biomeFor(dex) {
        if (dex < 1 || dex > 151) { return 0; }   // eggs live in the meadow
        return BIOMES.substring(dex - 1, dex).toNumber();
    }

    // Same hours as TamaPoke: night before 6 and from 20, sunrise before 8, sunset from 18.
    function timeSlot(hour) {
        if (hour < 6 || hour >= 20) { return 3; }
        if (hour < 8) { return 0; }
        if (hour < 18) { return 1; }
        return 2;
    }

    function background(biome, slot) {
        var ids = [
%s
        ];
        return ids[biome * 4 + slot];
    }
}
''' % (digits, "\n".join("            " + ", ".join("Rez.Drawables.bg%d_%s" % (b, t) for t in TIMES) + "," for b in range(7))))

counts = {BIOMES[i]: digits.count(str(i)) for i in range(7)}
print("backgrounds:", len(xml), "| Kanto per biome:", counts)
